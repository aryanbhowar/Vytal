"""Write the evaluation report, model card and figures for a trained model.

Every number in these documents is read from the model's metadata, which the
training script computed on held-out data. Nothing is typed in by hand.
"""

import matplotlib

matplotlib.use("Agg")  # file output only, no window

import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from sklearn.metrics import precision_recall_curve, roc_curve  # noqa: E402

from ml.feature_definitions.feature_schema import feature_definition  # noqa: E402
from ml.training import model_training_config as cfg  # noqa: E402

TITLES = {"heart": "Heart (reported coronary heart disease or heart attack)",
          "respiratory": "Respiratory (reported COPD, emphysema or chronic bronchitis)"}


def pct(value: float | None, digits: int = 1) -> str:
    return "—" if value is None else f"{value * 100:.{digits}f}%"


def num(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def save_figures(model_id: str, y_true: np.ndarray, probability: np.ndarray, metadata: dict) -> dict:
    cfg.FIGURES_DIR.mkdir(parents=True, exist_ok=True)
    test = metadata["evaluation"]["test"]
    paths = {}

    fpr, tpr, _ = roc_curve(y_true, probability)
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot(fpr, tpr, label=f"Logistic regression (AUC {test['roc_auc']:.3f})")
    ax.plot([0, 1], [0, 1], linestyle="--", color="grey", label="No skill (AUC 0.5)")
    ax.set(xlabel="False positive rate (1 − specificity)", ylabel="True positive rate (sensitivity)",
           title="ROC curve, test set")
    ax.legend(loc="lower right")
    paths["roc"] = cfg.FIGURES_DIR / f"{model_id}_roc_curve.png"
    fig.savefig(paths["roc"], dpi=120, bbox_inches="tight")
    plt.close(fig)

    precision, recall, _ = precision_recall_curve(y_true, probability)
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot(recall, precision, label=f"Logistic regression (AP {test['pr_auc']:.3f})")
    ax.axhline(y_true.mean(), linestyle="--", color="grey", label=f"No skill (prevalence {y_true.mean():.3f})")
    ax.set(xlabel="Recall (sensitivity)", ylabel="Precision", title="Precision–recall curve, test set")
    ax.legend(loc="upper right")
    paths["pr"] = cfg.FIGURES_DIR / f"{model_id}_precision_recall_curve.png"
    fig.savefig(paths["pr"], dpi=120, bbox_inches="tight")
    plt.close(fig)

    table = test["calibration_table"]
    predicted = [row["mean_predicted"] for row in table]
    observed = [row["observed_rate"] for row in table]
    upper = max(predicted + observed) * 1.1
    fig, ax = plt.subplots(figsize=(5, 5))
    ax.plot([0, upper], [0, upper], linestyle="--", color="grey", label="Perfect calibration")
    ax.plot(predicted, observed, marker="o", label="Model (10 equal-size groups)")
    ax.set(xlabel="Mean estimate in group", ylabel="Share who reported the condition",
           title="Calibration, test set", xlim=(0, upper), ylim=(0, upper))
    ax.legend(loc="upper left")
    paths["calibration"] = cfg.FIGURES_DIR / f"{model_id}_calibration.png"
    fig.savefig(paths["calibration"], dpi=120, bbox_inches="tight")
    plt.close(fig)
    return {name: f"figures/{path.name}" for name, path in paths.items()}


def _readable(feature: str) -> str:
    return feature_definition(feature)["question"]


def evaluation_report(metadata: dict, figures: dict) -> str:
    model_id = metadata["model_id"]
    ev = metadata["evaluation"]
    test, val, base = ev["test"], ev["validation"], ev["test_prevalence_baseline"]
    cm = test["confusion_matrix"]
    temporal = ev["temporal_check_train_2022_2023_test_2024"]
    hgb = ev["comparison_hist_gradient_boosting"]["test"]
    rows = metadata["training_data"]["rows"]
    lines = [
        f"# Model evaluation report: {TITLES[model_id]}",
        "",
        f"_Generated by `ml/training/train_binary_risk_model.py` on {metadata['created']} for model "
        f"`{metadata['artifact_file']}` (version {metadata['model_version']}). Every number below was computed "
        "by the training script; nothing is entered by hand. Re-running training regenerates this file._",
        "",
        "## What the model estimates",
        "",
        f"{metadata['outcome_description']} The model learns which combinations of answers go with **having "
        "reported** the condition in the survey. It does not predict whether a person will develop the condition, "
        "and it is not a diagnosis.",
        "",
        "## Data and method",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Data | {metadata['training_data']['source']} |",
        f"| Rows | train {rows['train']:,} · validation {rows['validation']:,} · test {rows['test']:,} (stratified by outcome and year, seed {cfg.SEED}) |",
        f"| Outcome rate in training data | {pct(metadata['training_data']['training_prevalence'], 2)} (unweighted sample) |",
        f"| Weighted US adult estimate | {pct(metadata['training_data']['weighted_us_adult_prevalence'], 2)} (CDC survey weights, all respondents with a valid answer) |",
        f"| Features | {', '.join(metadata['features'])} |",
        f"| Algorithm | {metadata['algorithm']} |",
        f"| BMI form | {metadata['bmi_form']} (validation log loss: linear {num(metadata['bmi_form_validation_log_loss']['linear'], 5)}, spline {num(metadata['bmi_form_validation_log_loss']['spline'], 5)}; lower is better) |",
        f"| Calibration | {metadata['calibration_method']} (validation before calibration: ECE {pct(ev['validation_before_calibration']['expected_calibration_error'], 2)}, slope {num(ev['validation_before_calibration']['calibration_slope'])}) |",
        "",
        "The test set was used once, after every choice (BMI form, calibration, threshold) had been made on the validation set.",
        "",
        "## Results on the test set",
        "",
        "| Metric | Model | Baseline: same estimate for everyone | What it means |",
        "|---|---|---|---|",
        f"| ROC-AUC | {num(test['roc_auc'])} | 0.500 | Chance that a random person who reported the condition gets a higher estimate than a random person who did not |",
        f"| ROC-AUC, survey-weighted | {num(test['roc_auc_survey_weighted'])} | 0.500 | The same, weighting respondents to represent US adults |",
        f"| PR-AUC (average precision) | {num(test['pr_auc'])} | {num(base['pr_auc'])} | Precision averaged over all recall levels; the baseline equals the outcome rate |",
        f"| Brier score | {num(test['brier_score'], 4)} | {num(base['brier_score'], 4)} | Mean squared error of the estimates (lower is better) |",
        f"| Log loss | {num(test['log_loss'], 4)} | {num(base['log_loss'], 4)} | Penalises confident wrong estimates (lower is better) |",
        f"| Expected calibration error | {pct(test['expected_calibration_error'], 2)} | — | Average gap between estimate and observed rate across 10 groups |",
        f"| Calibration slope / intercept | {num(test['calibration_slope'])} / {num(test['calibration_intercept'])} | — | 1 / 0 is perfect; slope below 1 means estimates are too spread out |",
        "",
        f"### At the reporting threshold ({pct(test['threshold'], 1)}, chosen as maximum F1 on validation)",
        "",
        "A threshold turns estimates into yes/no flags only so that standard metrics can be reported. **Vytal does not "
        "show users a yes/no result.**",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Sensitivity (recall) | {pct(test['recall_sensitivity'])} of people who reported the condition were flagged |",
        f"| Specificity | {pct(test['specificity'])} of people who did not were not flagged |",
        f"| Precision | {pct(test['precision'])} of flagged people had reported the condition |",
        f"| F1 | {num(test['f1'])} |",
        f"| Share of people flagged | {pct(test['flagged_share'])} |",
        f"| Accuracy (for reference only) | {pct(test['accuracy'])}; predicting \"no\" for everyone would score {pct(1 - test['prevalence'])} |",
        "",
        "Confusion matrix (test set):",
        "",
        "| | Flagged | Not flagged |",
        "|---|---|---|",
        f"| Reported the condition | {cm['true_positive']:,} (true positive) | {cm['false_negative']:,} (false negative) |",
        f"| Did not report it | {cm['false_positive']:,} (false positive) | {cm['true_negative']:,} (true negative) |",
        "",
        "## Class imbalance",
        "",
        f"Only {pct(test['prevalence'])} of test respondents reported the condition. That is why accuracy is misleading "
        "(saying \"no\" to everyone is highly accurate) and why precision is modest at any useful sensitivity: even a "
        "good ranking flags many people who did not report the condition. The model was trained without class "
        "weighting so that its estimates stay on the true scale (D-009); imbalance only affects the reporting threshold.",
        "",
        "## Calibration",
        "",
        "| Group (by estimate) | People | Mean estimate | Observed rate |",
        "|---|---|---|---|",
    ]
    for i, row in enumerate(test["calibration_table"], 1):
        lines.append(f"| {i} | {row['count']:,} | {pct(row['mean_predicted'], 2)} | {pct(row['observed_rate'], 2)} |")
    lines += [
        "",
        f"![Calibration]({figures['calibration']}) ![ROC]({figures['roc']}) ![Precision-recall]({figures['pr']})",
        "",
        "## Presentation bands (what users see)",
        "",
        "Bands describe where a person's estimate falls among the **training-set respondents**: Low = below the 50th "
        "percentile, Moderate = 50th–75th, Elevated = 75th–90th, High = 90th and above. They are **not clinical risk "
        "thresholds**. The table shows how often test-set respondents in each band actually reported the condition.",
        "",
        "| Band | Estimate range | Share of test respondents | Observed rate in band | Mean estimate in band |",
        "|---|---|---|---|---|",
    ]
    cut = metadata["bands"]["probability_cutoffs"]
    ranges = {"low": f"below {pct(cut['moderate'], 2)}", "moderate": f"{pct(cut['moderate'], 2)}–{pct(cut['elevated'], 2)}",
              "elevated": f"{pct(cut['elevated'], 2)}–{pct(cut['high'], 2)}", "high": f"{pct(cut['high'], 2)} and above"}
    for band, info in ev["test_band_validation"].items():
        lines.append(f"| {band.capitalize()} | {ranges[band]} | {pct(info['share_of_respondents'])} "
                     f"| {pct(info['observed_prevalence'], 2)} | {pct(info['mean_estimate'], 2)} |")
    lines += [
        "",
        "## Subgroup results (bias check, test set)",
        "",
        "| Group | People | Outcome rate | Mean estimate | ROC-AUC | Sensitivity | Specificity | Calibration error |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for dimension, groups in ev["test_subgroups"].items():
        for label, s in groups.items():
            lines.append(f"| {dimension}: {label} | {s['rows']:,} | {pct(s['prevalence'])} | {pct(s['mean_predicted'])} "
                         f"| {num(s['roc_auc'])} | {pct(s['recall_sensitivity'])} | {pct(s['specificity'])} "
                         f"| {pct(s['expected_calibration_error'], 2)} |")
    lines += [
        "",
        "ROC-AUC within an age group is lower than overall because age itself is a strong signal; within a group the "
        "model must rely on the other answers. Sensitivity differs by group mainly because outcome rates differ "
        "(one threshold flags more people in higher-rate groups).",
        "",
        "## Which answers matter most (test set)",
        "",
        "Mean absolute contribution to the log-odds score per person, using the same method as the explanations "
        "shown to users. This is association within this model, not cause.",
        "",
        "| Feature | Mean absolute contribution |",
        "|---|---|",
    ]
    for feature, value in ev["test_global_importance"].items():
        lines.append(f"| {_readable(feature)} | {num(value)} |")
    lines += [
        "",
        "## Robustness checks (reported only)",
        "",
        "| Check | ROC-AUC | PR-AUC | Brier | Calibration error |",
        "|---|---|---|---|---|",
        f"| Deployed model, test set | {num(test['roc_auc'])} | {num(test['pr_auc'])} | {num(test['brier_score'], 4)} | {pct(test['expected_calibration_error'], 2)} |",
        f"| Trained on 2022–2023 only, tested on 2024 ({temporal['test_rows']:,} rows) | {num(temporal['roc_auc'])} | {num(temporal['pr_auc'])} | {num(temporal['brier_score'], 4)} | {pct(temporal['expected_calibration_error'], 2)} |",
        f"| Gradient boosting comparison (not deployed) | {num(hgb['roc_auc'])} | {num(hgb['pr_auc'])} | {num(hgb['brier_score'], 4)} | {pct(hgb['expected_calibration_error'], 2)} |",
        "",
        "Logistic regression is deployed because its per-answer explanations are exact and easy to check (D-008). "
        "The comparison shows how much accuracy, if any, that choice costs.",
        "",
        "## Limitations",
        "",
        "- Self-reported, \"ever told\" outcomes; undiagnosed people count as \"no\".",
        "- Cross-sectional data: answers such as smoking may have changed after diagnosis. Associations, not causes.",
        "- US adults in a telephone survey; may not transfer to other populations.",
        "- Complete-case data (about 15–19% of respondents excluded for unusable answers).",
        "- Metrics treat respondents as independent and ignore the survey's strata and clusters.",
        "- Not clinically validated; not for diagnosis or treatment decisions.",
    ]
    if model_id == "heart":
        lines.append("- Blood pressure and cholesterol were not available across 2022–2024 and are not inputs.")
    else:
        lines.append("- The outcome groups COPD, emphysema and chronic bronchitis; asthma is an input, and some asthma may be misdiagnosed as COPD or vice versa.")
    return "\n".join(lines) + "\n"


def model_card(metadata: dict) -> str:
    model_id = metadata["model_id"]
    test = metadata["evaluation"]["test"]
    return "\n".join([
        f"# Model card: Vytal {model_id} model v{metadata['model_version']}",
        "",
        f"_Generated from `{metadata['artifact_file']}` metadata on {metadata['created']}. Full results: "
        f"[{model_id}_model_evaluation_report.md]({model_id}_model_evaluation_report.md)._",
        "",
        "## Model details",
        "",
        f"- **Type:** {metadata['algorithm']}; BMI as {metadata['bmi_form']}; calibration: {metadata['calibration_method']}.",
        f"- **Artifact:** `models/{model_id}/{metadata['artifact_file']}`, SHA-256 `{metadata['artifact_sha256']}` (checked before loading).",
        f"- **Software:** scikit-learn {metadata['dependencies']['scikit-learn']}, Python {metadata['dependencies']['python']}. Loading with other versions is not supported.",
        "",
        "## Intended use",
        "",
        "- Health-awareness information inside Vytal: an estimate of how often people with similar survey answers "
        "reported the condition, shown with its limitations and general, non-prescriptive suggestions.",
        "",
        "## Out-of-scope uses",
        "",
        "- Diagnosis, screening decisions, treatment, triage or insurance/employment decisions.",
        "- Predicting future onset of disease.",
        "- Populations outside US adults, or people under 18.",
        "- Reassuring anyone with symptoms: chest pain or severe breathlessness need urgent care regardless of any estimate.",
        "",
        "## Training data",
        "",
        f"- {metadata['training_data']['source']}; {metadata['training_data']['rows']['train']:,} training rows.",
        f"- Outcome: {metadata['outcome_description']}",
        f"- Inputs: {', '.join(_readable(f) for f in metadata['features'])}.",
        "- See `datasets/DATA_SOURCES.md` for provenance, exclusions and terms of use.",
        "",
        "## Performance (held-out test set)",
        "",
        f"- ROC-AUC {num(test['roc_auc'])}; PR-AUC {num(test['pr_auc'])} (outcome rate {pct(test['prevalence'])}); "
        f"Brier {num(test['brier_score'], 4)}; expected calibration error {pct(test['expected_calibration_error'], 2)}.",
        f"- At the reporting threshold: sensitivity {pct(test['recall_sensitivity'])}, specificity "
        f"{pct(test['specificity'])}, precision {pct(test['precision'])}.",
        "- Subgroup results by sex, age group and survey year are in the evaluation report.",
        "",
        "## Interpretation",
        "",
        "- **Model estimate:** the model's estimated share of similar respondents who reported the condition"
        + (" (calibrated)." if metadata["calibrator_used"] else "; validation showed it is well calibrated, so no recalibration was applied."),
        "- **Survey prevalence:** the weighted share of all US adult respondents who reported it "
        f"({pct(metadata['training_data']['weighted_us_adult_prevalence'], 1)}).",
        "- **Band:** position of the estimate among survey respondents (percentile cut-offs 50/75/90). Not a clinical category.",
        "- **Clinical risk:** not estimated by Vytal. It requires clinical assessment, measurements (e.g. blood pressure, cholesterol) and validated tools.",
        "",
        "## Ethical considerations and limitations",
        "",
        "- Self-reported, cross-sectional data; associations, not causes. Race, income and education are deliberately not inputs.",
        "- Not clinically validated, not a medical device.",
        "",
    ])


def write_evaluation_documents(metadata: dict, y_true: np.ndarray, probability: np.ndarray) -> None:
    model_id = metadata["model_id"]
    metadata["calibrator_used"] = metadata["calibration_method"] != "none needed"
    figures = save_figures(model_id, y_true, probability, metadata)
    cfg.EVALUATION_DOCS_DIR.mkdir(parents=True, exist_ok=True)
    (cfg.EVALUATION_DOCS_DIR / f"{model_id}_model_evaluation_report.md").write_text(
        evaluation_report(metadata, figures), encoding="utf-8")
    (cfg.EVALUATION_DOCS_DIR / f"{model_id}_model_card.md").write_text(model_card(metadata), encoding="utf-8")
